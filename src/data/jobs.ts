/** Relative calendar date helper so "due today / soon" stays meaningful. */
function daysFromNow(offset: number): string {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() + offset);
  return date.toISOString().slice(0, 10);
}

